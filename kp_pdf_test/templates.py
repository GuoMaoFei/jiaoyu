# 模板注册表
# ============================================================
_TEMPLATES: dict[str, PDFGenConfig] = {
    "math_grade1": MATH_GRADE1_TEMPLATE,
    "math_grade3": MATH_GRADE3_TEMPLATE,
    "chinese_grade2": CHINESE_GRADE2_TEMPLATE,
}


def get_template(name: str) -> PDFGenConfig:
    """获取预定义模板

    Args:
        name: 模板名称，支持 math_grade1, math_grade3, chinese_grade2

    Returns:
        PDFGenConfig 配置对象

    Raises:
        ValueError: 模板名称不存在时
    """
    if name not in _TEMPLATES:
        available = ", ".join(_TEMPLATES.keys())
        raise ValueError(f"模板 '{name}' 不存在，可用模板: {available}")
    return _TEMPLATES[name]


def list_templates() -> list[str]:
    """列出所有可用模板名称"""
    return list(_TEMPLATES.keys())
